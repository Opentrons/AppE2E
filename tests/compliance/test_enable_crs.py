"""Enable Compliance Ready Software from Robot Settings → Advanced.

This is permanent. Complete setup creates the service, admin, and recovery
accounts, turns access control on, clears run history and calibrations, and
restarts the robot. Run it only while CRS is still off.

The encryption key rotates on the robot screen. The test pauses and asks for
it in the workflow runner (or on stdin when the runner is not attached).
Service and recovery passwords are generated by the app; the runner shows
them with the admin account before Complete setup, and writes them to
``artifacts/crs_accounts.json`` until the next Enable CRS run overwrites them.
"""

from __future__ import annotations

import pytest
from playwright.sync_api import Page

from automation.app_helpers.crs_accounts import CrsAccount, CrsReportedAccount, report_crs_accounts
from automation.app_helpers.test_progress import log_done, log_step
from automation.app_pages import RobotSettingsPage
from automation.app_pages_crs import EnableCRSWizardPage


@pytest.mark.crs
@pytest.mark.dismiss_blockers
@pytest.mark.timeout(3600)
@pytest.mark.workflow(
    group="compliance",
    section="Compliance Setup",
    label="Enable CRS (permanent, resets the robot)",
    order=10,
)
def test_enable_crs(run_local_app: Page, robot_name: str, crs_user: CrsAccount) -> None:
    """Turn Compliance Ready on and report the three accounts."""
    page = run_local_app
    settings = RobotSettingsPage(page, robot_name=robot_name)
    wizard = EnableCRSWizardPage(page)

    log_step(f"Open Advanced on {robot_name} and start Enable CRS")
    service_pin = wizard.open_from_advanced(settings)
    log_done("Enable CRS wizard is open")

    log_step("Submit the service PIN")
    wizard.submit_service_pin(service_pin)
    log_done("Encryption key step is open")

    log_step("Wait for the encryption key from the robot screen")
    wizard.submit_encryption_key_from_operator()
    log_done("Encryption key accepted")

    log_step("Record the generated service account")
    service = wizard.read_displayed_account(role="Service", expected_username=wizard.SERVICE_USERNAME)
    wizard.continue_from_service_account()
    log_done("Service account recorded")

    log_step(f"Create admin {crs_user.username!r}")
    wizard.fill_admin_identity(crs_user.username, crs_user.legal_name)
    wizard.fill_admin_password(crs_user.password)
    log_done("Admin account entered")

    log_step("Record the generated recovery account")
    recovery = wizard.read_displayed_account(role="Recovery", expected_username=wizard.RECOVERY_USERNAME)
    admin = CrsReportedAccount(
        role="Admin",
        username=crs_user.username,
        password=crs_user.password,
        legal_name=crs_user.legal_name,
    )
    report_crs_accounts((service, admin, recovery), service_pin=service_pin)
    log_done("Accounts sent to the workflow runner")

    log_step("Complete setup and wait for the robot to restart")
    wizard.complete_setup()
    log_done("Compliance Ready Software is enabled")
