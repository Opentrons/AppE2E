"""Enable Compliance Ready Software wizard on Robot Settings → Advanced.

The service PIN is ``{robot serial}-0000``. The encryption key rotates on the
robot screen, so the operator types it into the workflow runner while this
page is open. Service and recovery passwords are generated by the app and
only shown in the wizard.
"""

from __future__ import annotations

import re

from playwright.sync_api import Locator, Page, expect

from automation.app_helpers.crs_accounts import CrsReportedAccount
from automation.app_helpers.locator_helpers import exact_text
from automation.app_helpers.ui_prompt import request_text
from automation.app_pages.base_app.app_base_page import AppBasePage
from automation.app_pages.base_app.robot_settings_page import RobotSettingsPage

_GENERATED_PASSWORD = re.compile(r"^[a-z]{3}(?:-[a-z]{3}){3}$")
_ENCRYPTION_ATTEMPTS = 3


class EnableCRSWizardPage(AppBasePage):
    """Drive the desktop Enable CRS wizard."""

    ENABLE_BUTTON = "Enable CRS"
    CONFIRM_ENABLE = "Enable Compliance Ready Software"
    SERVICE_PIN = "Service PIN"
    ENCRYPTION_KEY = "Robot encryption key"
    SERVICE_STEP = "Create Service account"
    ADMIN_STEP = "Create Admin account"
    PASSWORD_STEP = "Create password"
    RECOVERY_STEP = "Recovery account details"
    COMPLETE = "Complete setup"
    RESTARTING = "Restarting robot"
    PIN_REJECTED = "Incorrect service PIN"
    KEY_REJECTED = "Invalid encryption key. Try again."
    SUBMISSION_ERROR = "Unable to enable Compliance Ready Software. Try again."
    SERVICE_USERNAME = "service"
    RECOVERY_USERNAME = "recovery"
    # Robot restart after Complete setup waits for the robot to come back.
    RESTART_TIMEOUT_MS = 1_200_000

    def __init__(self, page: Page) -> None:
        """Bind the desktop page that hosts the wizard."""
        super().__init__(page)

    @property
    def dialog(self) -> Locator:
        """Modal shell for the current wizard step."""
        return self.page.get_by_role("dialog", name="ModalShell_ModalArea")

    @property
    def enable_button(self) -> Locator:
        """Advanced-tab button that opens the wizard."""
        return self.page.get_by_role("button", name=exact_text(self.ENABLE_BUTTON))

    @property
    def service_pin_input(self) -> Locator:
        """Service PIN field on the first wizard step."""
        return self.dialog.get_by_role("textbox", name=exact_text(self.SERVICE_PIN))

    @property
    def encryption_key_input(self) -> Locator:
        """Encryption key field. The matching key is on the robot screen."""
        return self.dialog.get_by_role("textbox", name=exact_text(self.ENCRYPTION_KEY))

    @property
    def next_button(self) -> Locator:
        """Advance the current wizard step."""
        return self.dialog.get_by_role("button", name=exact_text("Next"))

    def open_from_advanced(self, settings: RobotSettingsPage) -> str:
        """Open Advanced, require Enable CRS, and return ``{serial}-0000``."""
        serial = settings.read_robot_serial()
        pin = f"{serial}-0000"
        button = self.enable_button
        button.scroll_into_view_if_needed()
        expect(button).to_be_visible()
        if button.is_disabled():
            raise AssertionError(
                "Enable CRS is disabled. Compliance Ready is already on, the robot is busy, "
                "or the access-control status has not loaded."
            )
        button.click()
        expect(self.service_pin_input).to_be_visible()
        return pin

    def submit_service_pin(self, pin: str) -> None:
        """Submit the service PIN and wait for the encryption-key step."""
        self.service_pin_input.fill(pin)
        self.dialog.get_by_role("button", name=exact_text(self.CONFIRM_ENABLE)).click()
        rejected = self.dialog.get_by_text(exact_text(self.PIN_REJECTED))
        expect(self.encryption_key_input.or_(rejected)).to_be_visible()
        if rejected.is_visible():
            raise AssertionError(f"Service PIN {pin} was rejected.")

    def submit_encryption_key_from_operator(self) -> None:
        """Pause for the key on the robot screen, then retry when it is rejected."""
        expect(self.dialog.get_by_text(exact_text("Verify robot encryption key"))).to_be_visible()
        for attempt in range(1, _ENCRYPTION_ATTEMPTS + 1):
            if attempt == 1:
                message = (
                    "The robot screen is showing a rotating encryption key. "
                    "Type the key you see right now. It changes on a timer, so use the current one."
                )
            else:
                message = "That key was rejected. Read the robot screen again and enter the key it shows now."
            key = request_text(
                title="Robot encryption key",
                message=message,
                placeholder="word-word-word",
            )
            self.encryption_key_input.fill(key)
            # A rejected key stays on screen until the field changes. Wait for it
            # to clear so the next check is for this attempt.
            expect(self.dialog.get_by_text(exact_text(self.KEY_REJECTED))).to_be_hidden()
            self.next_button.click()
            accepted = self.dialog.get_by_text(exact_text(self.SERVICE_STEP))
            rejected = self.dialog.get_by_text(exact_text(self.KEY_REJECTED))
            expect(accepted.or_(rejected)).to_be_visible(timeout=30_000)
            if accepted.is_visible():
                return
        raise AssertionError(f"Encryption key was rejected {_ENCRYPTION_ATTEMPTS} times.")

    def read_displayed_account(self, *, role: str, expected_username: str) -> CrsReportedAccount:
        """Read the username and generated password shown on the current step."""
        username = self._labeled_value("Username")
        password = self._labeled_value("Password")
        if username != expected_username:
            raise AssertionError(f"Expected {role} username {expected_username!r}, saw {username!r}.")
        if _GENERATED_PASSWORD.fullmatch(password) is None:
            raise AssertionError(f"{role} password {password!r} is not the generated word-word-word-word form.")
        return CrsReportedAccount(role=role, username=username, password=password)

    def continue_from_service_account(self) -> None:
        """Leave the service-account step for admin identity."""
        expect(self.dialog.get_by_text(exact_text(self.SERVICE_STEP))).to_be_visible()
        self.next_button.click()
        expect(self.dialog.get_by_text(exact_text(self.ADMIN_STEP))).to_be_visible()

    def fill_admin_identity(self, username: str, legal_name: str) -> None:
        """Enter the admin username and legal name."""
        self.dialog.get_by_role("textbox", name=exact_text("Username")).fill(username)
        self.dialog.get_by_role("textbox", name=exact_text("Legal name")).fill(legal_name)
        self.next_button.click()
        expect(self.dialog.get_by_text(exact_text(self.PASSWORD_STEP))).to_be_visible()

    def fill_admin_password(self, password: str) -> None:
        """Enter and confirm the admin password, then open recovery details."""
        self.dialog.get_by_role("textbox", name=exact_text("Password")).fill(password)
        self.dialog.get_by_role("textbox", name=exact_text("Confirm password")).fill(password)
        self.next_button.click()
        expect(self.dialog.get_by_text(exact_text(self.RECOVERY_STEP))).to_be_visible()

    def complete_setup(self) -> None:
        """Finish the wizard and wait until the robot restart closes it."""
        complete = self.dialog.get_by_role("button", name=exact_text(self.COMPLETE))
        expect(complete).to_be_visible()
        expect(self.dialog.get_by_role("button", name=exact_text("Back"))).to_be_visible()
        complete.click()
        restarting = self.dialog.get_by_text(exact_text(self.RESTARTING))
        failed = self.dialog.get_by_text(exact_text(self.SUBMISSION_ERROR))
        expect(restarting.or_(failed)).to_be_visible(timeout=60_000)
        if failed.is_visible():
            raise AssertionError(self.SUBMISSION_ERROR)
        expect(self.dialog).to_be_hidden(timeout=self.RESTART_TIMEOUT_MS)
        expect(self.page.get_by_role("button", name=exact_text("Log in"))).to_be_visible(timeout=120_000)

    def _labeled_value(self, label: str) -> str:
        label_node = self.dialog.get_by_text(exact_text(label))
        expect(label_node).to_be_visible()
        value = label_node.locator("xpath=following-sibling::*[1]")
        expect(value).to_be_visible()
        text = value.inner_text().strip()
        if not text:
            raise AssertionError(f"The CRS wizard did not show a {label}.")
        return text
